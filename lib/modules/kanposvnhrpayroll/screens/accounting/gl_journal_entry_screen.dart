        ];
      case EntryType.payment:
        final crAcct = _paymentMethod == 'cash' ? '111' : '112';
        final crName = _paymentMethod == 'cash' ? 'Tiền mặt' : 'Tiền gửi NH';
        return [
          _previewRow('Dr', '334', 'Chi lương NLĐ', AppTheme.danger),
          _previewRow('Cr', crAcct, crName, AppTheme.accent),
        ];
      case EntryType.bonus:
        return [
          _previewRow('Dr', '6422', 'Chi phí thưởng', AppTheme.danger),
          _previewRow('Cr', '334', 'Phải trả NLĐ', AppTheme.accent),
        ];
      case EntryType.advance:
        return [
          _previewRow('Dr', '141', 'Tạm ứng', AppTheme.danger),
          _previewRow('Cr', '112', 'Tiền gửi NH', AppTheme.accent),
        ];
      default:
        return [
          const Text('Chọn loại để xem trước cấu trúc hạch toán',
              style: TextStyle(fontSize: 12, color: AppTheme.textSecondary)),
        ];
    }
  }

  static Widget _previewRow(String side, String account, String desc, Color color) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 2),
      child: Row(
        children: [
          SizedBox(
            width: 24,
            child: Text(side,
                style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold, color: color)),
          ),
          const SizedBox(width: 8),
          SizedBox(
            width: 50,
            child: Text(account, style: TextStyle(fontSize: 12, fontWeight: FontWeight.w600, color: color)),
          ),
          Expanded(
            child: Text(desc, style: const TextStyle(fontSize: 12, color: AppTheme.textSecondary)),
          ),
        ],
      ),
    );
  }

  static IconData _typeIcon(EntryType type) {
    switch (type) {
      case EntryType.salary: return Icons.account_balance_wallet;
      case EntryType.insurance: return Icons.health_and_safety;
      case EntryType.pit: return Icons.receipt;
      case EntryType.payment: return Icons.payments;
      case EntryType.advance: return Icons.money;
      case EntryType.bonus: return Icons.card_giftcard;
      case EntryType.adjustment: return Icons.tune;
      case EntryType.openingBalance: return Icons.account_balance_wallet_outlined;
      case EntryType.other: return Icons.receipt_long;
    }
  }

  static String _typeLabel(EntryType t) {
    switch (t) {
      case EntryType.salary: return 'Lương (Dr 6422 / Cr 334+338x)';
      case EntryType.insurance: return 'BHXH/BHYT/BHTN (Dr 6422 / Cr 338x)';
      case EntryType.pit: return 'Thuế TNCN (Dr 334 / Cr 3335)';
      case EntryType.payment: return 'Chi tiền (Dr 334 / Cr 112)';
      case EntryType.advance: return 'Tạm ứng (Dr 141 / Cr 112)';
      case EntryType.bonus: return 'Thưởng (Dr 6422 / Cr 334)';
      case EntryType.adjustment: return 'Điều chỉnh';
      case EntryType.openingBalance: return 'Số dư đầu kỳ';
      case EntryType.other: return 'Nghiệp vụ khác';
    }
  }

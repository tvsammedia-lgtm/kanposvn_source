/// Màn hình nhập bút toán kế toán GL cho HR Payroll.
/// Hỗ trợ tự động theo loại (lương, BHXH, TNCN, chi tiền, thưởng, tạm ứng)
/// và nhập tay DR/CR theo dòng với đối tượng nhân viên/tài xế.
class GlJournalEntryScreen extends ConsumerStatefulWidget {
  final EntryType initialType;
  final int year;
  final int month;

  const GlJournalEntryScreen({
    super.key,
    this.initialType = EntryType.salary,
    required this.year,
    required this.month,
  });

  @override
  ConsumerState<GlJournalEntryScreen> createState() => _GlJournalEntryScreenState();
}

class _GlJournalEntryScreenState extends ConsumerState<GlJournalEntryScreen> {
  late EntryType _type;
  late int _year;
  late int _month;
  final _descCtrl = TextEditingController();
  String _paymentMethod = 'bank';
  bool _isAutoGen = true;
  final List<_LineData> _lines = [_LineData()];
  bool _saving = false;

  @override
  void initState() {
    super.initState();
    _type = widget.initialType;
    _year = widget.year;
    _month = widget.month;
  }

  @override
  void dispose() {
    _descCtrl.dispose();
    for (final l in _lines) {
      l.dispose();
    }
    super.dispose();
  }

  void _addLine() => setState(() => _lines.add(_LineData()));

  void _removeLine(int i) {
    if (_lines.length <= 1) return;
    setState(() {
      _lines[i].dispose();
      _lines.removeAt(i);
    });
  }

  // ══════════════════ AUTO GENERATE ══════════════════
  Future<void> _autoGenerate() async {
    if (_saving) return;
    setState(() => _saving = true);

    try {
      final db = ref.read(dbProvider);
      final payrolls = await db.getPayrollByMonth(_year, _month);

      if (payrolls.isEmpty && _type != EntryType.advance) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(content: Text('Không có dữ liệu lương tháng này')),
          );
        }
        return;
      }

      AccountingEntry? entry;
      List<AccountingEntryLine> lines = [];

      switch (_type) {
        case EntryType.salary:
          entry = PayrollCalculatorService.buildSalaryJournalEntry(
            year: _year, month: _month, payrolls: payrolls,
          );
          entry.isAutoGenerated = true;
          entry.description = 'Hạch toán lương tháng $_month/$_year (${payrolls.length} người)';
          lines = PayrollCalculatorService.buildSalaryEntryLines(
            journalID: entry.journalID, payrolls: payrolls,
          );
          break;
        case EntryType.insurance:
          entry = _buildInsuranceEntry(payrolls);
          lines = _buildInsuranceLines(entry.journalID, payrolls);
          break;
        case EntryType.pit:
          entry = PayrollCalculatorService.buildPitJournalEntry(
            year: _year, month: _month, payrolls: payrolls,
          );
          entry.isAutoGenerated = true;
          entry.description = 'Khấu trừ thuế TNCN tháng $_month/$_year';
          final totalPit = payrolls.fold<double>(0, (s, p) => s + p.personalIncomeTax);
          lines = [
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 1
              ..debitAccountNumber = '334'
              ..creditAccountNumber = ''
              ..amount = totalPit
              ..description = 'Dr 334 - Phải trả NLĐ',
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 2
              ..debitAccountNumber = ''
              ..creditAccountNumber = '3335'
              ..amount = totalPit
              ..description = 'Cr 3335 - Thuế TNCN',
          ];
          break;
        case EntryType.payment:
          entry = PayrollCalculatorService.buildPaymentJournalEntry(
            year: _year, month: _month, payrolls: payrolls, paymentMethod: _paymentMethod,
          );
          entry.isAutoGenerated = true;
          entry.description = 'Chi lương tháng $_month/$_year qua ${_paymentMethod == 'cash' ? 'tiền mặt' : 'NH'}';
          final totalNet = payrolls.fold<double>(0, (s, p) => s + p.netSalary);
          final crAcct = _paymentMethod == 'cash' ? '111' : '112';
          lines = [
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 1
              ..debitAccountNumber = '334'
              ..creditAccountNumber = ''
              ..amount = totalNet
              ..description = 'Dr 334 - Chi lương NLĐ',
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 2
              ..debitAccountNumber = ''
              ..creditAccountNumber = crAcct
              ..amount = totalNet
              ..description = 'Cr $crAcct - Tiền gửi NH/tiền mặt',
          ];
          break;
        case EntryType.bonus:
          entry = PayrollCalculatorService.buildBonusJournalEntry(
            year: _year, month: _month, payrolls: payrolls,
          );
          if (entry.voucherNumber.isEmpty) {
            if (mounted) {
              ScaffoldMessenger.of(context).showSnackBar(
                const SnackBar(content: Text('Tháng này không có thưởng')),
              );
            }
            return;
          }
          entry.isAutoGenerated = true;
          final totalBonus = payrolls.fold<double>(0, (s, p) =>
              s + p.safetyBonus + p.fuelSavingBonus + p.kpiBonus + p.monthlyBonus + p.otherBonus);
          lines = [
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 1
              ..debitAccountNumber = '6422'
              ..creditAccountNumber = ''
              ..amount = totalBonus
              ..description = 'Dr 6422 - Chi phí thưởng',
            AccountingEntryLine()
              ..journalID = entry.journalID
              ..lineOrder = 2
              ..debitAccountNumber = ''
              ..creditAccountNumber = '334'
              ..amount = totalBonus
              ..description = 'Cr 334 - Phải trả NLĐ',
          ];
          break;
        case EntryType.advance:
          if (mounted) {
            ScaffoldMessenger.of(context).showSnackBar(
              const SnackBar(content: Text('Tạm ứng cần nhập tay — chọn Nhập tay DR/CR')),
            );
          }
          return;
        default:
          if (mounted) {
            ScaffoldMessenger.of(context).showSnackBar(
              const SnackBar(content: Text('Loại này cần nhập tay')),
            );
          }
          return;
      }

      await db.saveAccountingEntry(entry);
      await db.saveAccountingEntryLines(lines);

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Đã tạo bút toán ${entry.voucherNumber} (${lines.length} dòng)'),
            backgroundColor: AppTheme.success,
          ),
        );
        context.pop();
      }
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  AccountingEntry _buildInsuranceEntry(List<Payroll> payrolls) {
    final totalBhxhEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhxh);
    final totalBhytEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhyt);
    final totalBhtnEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhtn);
    final totalUnion = payrolls.fold<double>(0, (s, p) => s + p.unionFee);
    final total = totalBhxhEmp + totalBhytEmp + totalBhtnEmp + totalUnion;

    final seq = 6;
    final voucherNo = 'GL-${_year.toString().padLeft(4, '0')}/${_month.toString().padLeft(2, '0')}-${seq.toString().padLeft(3, '0')}';
    final journalID = '${PayrollCalculatorService.makeJournalID(_year, _month)}-INS';

    return AccountingEntry()
      ..voucherNumber = voucherNo
      ..journalID = journalID
      ..year = _year
      ..month = _month
      ..entryType = EntryType.insurance
      ..status = EntryStatus.draft
      ..postingDate = DateTime(_year, _month + 1, 5)
      ..documentDate = DateTime.now()
      ..refType = 4010
      ..description = 'Hạch toán BCNLĐ NSDL tháng $_month/$_year'
      ..totalDebit = total
      ..totalCredit = total
      ..isAutoGenerated = true
      ..createdBy = 'System';
  }

  List<AccountingEntryLine> _buildInsuranceLines(String journalID, List<Payroll> payrolls) {
    final totalBhxhEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhxh);
    final totalBhytEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhyt);
    final totalBhtnEmp = payrolls.fold<double>(0, (s, p) => s + p.employerBhtn);
    final totalUnion = payrolls.fold<double>(0, (s, p) => s + p.unionFee);

    var n = 0;
    return [
      AccountingEntryLine()
        ..journalID = journalID
        ..lineOrder = ++n
        ..debitAccountNumber = '6422'
        ..creditAccountNumber = ''
        ..amount = totalBhxhEmp + totalBhytEmp + totalBhtnEmp + totalUnion
        ..description = 'Dr 6422 - Chi phí BCNLĐ',
      AccountingEntryLine()
        ..journalID = journalID
        ..lineOrder = ++n
        ..debitAccountNumber = ''
        ..creditAccountNumber = '3383'
        ..amount = totalBhxhEmp
        ..description = 'Cr 3383 - BHXH NSDL',
      AccountingEntryLine()
        ..journalID = journalID
        ..lineOrder = ++n
        ..debitAccountNumber = ''
        ..creditAccountNumber = '3384'
        ..amount = totalBhytEmp
        ..description = 'Cr 3384 - BHYT NSDL',
      AccountingEntryLine()
        ..journalID = journalID
        ..lineOrder = ++n
        ..debitAccountNumber = ''
        ..creditAccountNumber = '3385'
        ..amount = totalBhtnEmp
        ..description = 'Cr 3385 - BHTN NSDL',
      AccountingEntryLine()
        ..journalID = journalID
        ..lineOrder = ++n
        ..debitAccountNumber = ''
        ..creditAccountNumber = '3382'
        ..amount = totalUnion
        ..description = 'Cr 3382 - Kinh phí CĐ',
    ];
  }

  // ══════════════════ MANUAL SAVE ══════════════════
  Future<void> _saveManual() async {
    if (_saving) return;

    final desc = _descCtrl.text.trim();
    if (desc.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Nhập mô tả bút toán')),
      );
      return;
    }

    double totalDr = 0;
    double totalCr = 0;
    for (final l in _lines) {
      if (l.debitAccount.isEmpty || l.amount <= 0) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Mỗi dòng phải có tài khoản Nợ và số tiền > 0')),
        );
        return;
      }
      totalDr += l.amount;
      if (l.creditAccount.isNotEmpty) totalCr += l.amount;
    }
    if ((totalDr - totalCr).abs() > 0.5) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Tổng Nợ phải bằng Tổng Có')),
      );
      return;
    }

    setState(() => _saving = true);
    try {
      final journalID = 'JRN-${_year.toString().padLeft(4, '0')}${_month.toString().padLeft(2, '0')}-MANUAL-${DateTime.now().millisecondsSinceEpoch}';
      final voucherNo = 'GL-${_year.toString().padLeft(4, '0')}/${_month.toString().padLeft(2, '0')}-${DateTime.now().millisecondsSinceEpoch % 1000}';

      final entry = AccountingEntry()
        ..voucherNumber = voucherNo
        ..journalID = journalID
        ..year = _year
        ..month = _month
        ..entryType = _type
        ..status = EntryStatus.draft
        ..postingDate = DateTime(_year, _month, 15)
        ..documentDate = DateTime.now()
        ..refType = 4010
        ..description = desc
        ..totalDebit = totalDr
        ..totalCredit = totalDr
        ..isAutoGenerated = false
        ..createdBy = 'Nhập tay';

      final db = ref.read(dbProvider);
      await db.saveAccountingEntry(entry);

      final entryLines = <AccountingEntryLine>[];
      var order = 0;
      for (final l in _lines) {
        entryLines.add(AccountingEntryLine()
          ..journalID = journalID
          ..lineOrder = ++order
          ..debitAccountNumber = l.debitAccount
          ..creditAccountNumber = l.creditAccount
          ..amount = l.amount
          ..objectCode = l.objectCode.isNotEmpty ? l.objectCode : null
          ..departmentCode = l.deptCode.isNotEmpty ? l.deptCode : null
          ..description = l.desc.isNotEmpty ? l.desc : null
        );
      }
      await db.saveAccountingEntryLines(entryLines);

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Đã lưu bút toán nháp $voucherNo'),
            backgroundColor: AppTheme.success,
          ),
        );
        context.pop();
      }
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }


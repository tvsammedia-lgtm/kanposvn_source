  static String tr(String key, {String? param, Map<String, String>? params}) {
    final lang = locale.languageCode;
    String value = key;
    final raw = _translations[lang]?[key] ?? _translations['vi']?[key];
    if (raw is String) value = raw;
    if (param != null) {
      value = value.replaceAll('{count}', param).replaceAll('{amount}', param)
          .replaceAll('{name}', param).replaceAll('{module}', param)
          .replaceAll('{code}', param).replaceAll('{date}', param)
          .replaceAll('{time}', param).replaceAll('{orderId}', param)
          .replaceAll('{margin}', param).replaceAll('{period}', param)
          .replaceAll('{price}', param).replaceAll('{value}', param)
          .replaceAll('{allergy}', param).replaceAll('{status}', param)
          .replaceAll('{qty}', param).replaceAll('{unit}', param)
          .replaceAll('{hours}', param).replaceAll('{days}', param);
    }
    if (params != null) {
      for (final entry in params.entries) {
        value = value.replaceAll('{${entry.key}}', entry.value);
      }
    }
    return value;
  }

  static List<String> getDayLabels() {
    final lang = locale.languageCode;
    final labels = _translations[lang]?['day_labels'];
    if (labels is List<String>) return labels;
    final fallback = _translations['vi']!['day_labels'];
    return fallback is List<String> ? fallback : [];
  }

  static Map<String, String> getCategoryMap(String section) {
    final lang = locale.languageCode;
    final map = _translations[lang]?[section];
    if (map is Map<String, dynamic>) return map.cast<String, String>();
    final fallback = _translations['vi']?[section];
    if (fallback is Map<String, dynamic>) return fallback.cast<String, String>();
    return {};
  }
}

extension Translate on String {
  String get tr => AppTranslations.tr(this);
  String trParams(Map<String, String> params) => AppTranslations.tr(this, params: params);
}
